"""Rebuild hidden native-unit vectors from the independent datasheet oracle.

Deliberately imports neither source OS drivers nor hidden reference code.
Existing fixed-point and double algorithms bound allowed arithmetic variants.
No sensor accuracy tolerance is used for deterministic compensation checks.
"""
import hashlib
import json
from pathlib import Path
import runpy

HERE = Path(__file__).resolve().parent
ROOT=Path(__file__).resolve().parents[3]
BASIS=Path(__file__).resolve().parent


def render():
    oracle = runpy.run_path(str(BASIS / 'oracle.py'))
    rows = []
    records = []
    for case in json.loads((BASIS / 'cases.yaml').read_text())['vectors']:
        cal, raw = case['calibration'], case['raw']
        fixed = oracle['compensate'](cal, raw)
        double = oracle['compensate_double'](cal, raw)
        p32 = oracle['pressure_int32'](cal, raw, fixed['t_fine']) / 100.0
        variants = [[fixed['temperature_centi_c']/100, double[0]/100],
                    [fixed['humidity_centi_percent']/100, double[1]/100],
                    [fixed['pressure_q24_8_pa']/25600, double[2], p32]]
        # 0.011 covers integer T/H truncation; 0.02 hPa covers fixed-point
        # pressure quantization. Bounds also enclose the three documented paths.
        low = [min(x)-epsilon for x, epsilon in zip(variants, (.011, .011, .02))]
        high = [max(x)+epsilon for x, epsilon in zip(variants, (.011, .011, .02))]
        low[1], high[1] = max(0, low[1]), min(100, high[1])
        regs = oracle['calibration_registers'](cal)
        p, t, h = raw['pressure'], raw['temperature'], raw['humidity']
        regs[0xf7:0xff] = [p>>12, (p>>4)&255, (p&15)<<4,
                          t>>12, (t>>4)&255, (t&15)<<4, h>>8, h&255]
        rows.append('{"'+case['id']+'", {'+','.join(map(str,regs))+'}, {'+
                    ','.join(map(repr,low))+'}, {'+','.join(map(repr,high))+'}}')
        records.append({'id': case['id'], 'low': low, 'high': high,
                        'documented_algorithms': variants})
    header = ('/* Generated by render_vectors.py from independent datasheet mathematics. */\n'
              'struct vector { const char *name; uint8_t regs[256]; double low[3], high[3]; };\n'
              'static const struct vector vectors[] = {\n'+',\n'.join(rows)+'\n};\n')
    evidence = {'schema':'driverbench.native-bme280-vectors/v1',
                'inputs': {str(p.relative_to(ROOT)): hashlib.sha256(p.read_bytes()).hexdigest()
                           for p in (BASIS/'oracle.py', BASIS/'cases.yaml',
                                     ROOT/'benchmark/bme280/documents/datasheet.pdf')},
                'records': records}
    return header, evidence


if __name__ == '__main__':
    header, evidence = render()
    (HERE/'vectors.h').write_text(header)
    (HERE/'vectors.json').write_text(json.dumps(evidence, indent=2)+'\n')
